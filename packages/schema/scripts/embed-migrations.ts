// Embeds drizzle/sqlite/*.sql into src/migrations.gen.ts so migrate() needs no filesystem access.
// Run after drizzle-kit generate (the package "generate" script does both).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "drizzle", "sqlite");
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8")) as {
  entries: { idx: number; tag: string; when: number }[];
};
const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({
    tag: e.tag,
    statements: readFileSync(join(dir, `${e.tag}.sql`), "utf8").split("--> statement-breakpoint"),
  }));
const out = `// GENERATED by scripts/embed-migrations.ts from drizzle/sqlite. Do not edit.
export const sqliteMigrations: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(import.meta.dir, "..", "src", "migrations.gen.ts"), out);
console.log(`embedded ${migrations.length} sqlite migration(s)`);
